package org.techhouse.ops;

public enum OperationType {
    // @formatter:off
    BULK_SAVE(Scope.COLLECTION),
    SAVE(Scope.COLLECTION),
    FIND_BY_ID(Scope.COLLECTION),
    AGGREGATE(Scope.COLLECTION),
    DELETE(Scope.COLLECTION),
    CREATE_DATABASE(Scope.DATABASE),
    DROP_DATABASE(Scope.DATABASE),
    LIST_DATABASES(Scope.NONE),
    CREATE_COLLECTION(Scope.COLLECTION),
    DROP_COLLECTION(Scope.COLLECTION),
    LIST_COLLECTIONS(Scope.DATABASE),
    CREATE_INDEX(Scope.COLLECTION),
    DROP_INDEX(Scope.COLLECTION),
    REINDEX(Scope.COLLECTION),
    SAVE_SCHEMA(Scope.COLLECTION),
    DELETE_SCHEMA(Scope.COLLECTION),
    GET_SCHEMA(Scope.COLLECTION),
    CLOSE_CONNECTION(Scope.NONE),
    AUTHENTICATE(Scope.NONE),
    CREATE_USER(Scope.NONE),
    DELETE_USER(Scope.NONE),
    CHANGE_PERMISSIONS(Scope.NONE),
    SET_DATABASE_OWNERS(Scope.DATABASE),
    LIST_USERS(Scope.NONE),
    SET_PASSWORD(Scope.NONE),
    GET_DATABASE_STATS(Scope.DATABASE),
    LISTEN(Scope.COLLECTION),
    STOP_LISTEN(Scope.NONE),
    START_TRANSACTION(Scope.NONE),
    COMMIT_TRANSACTION(Scope.NONE),
    ROLLBACK_TRANSACTION(Scope.NONE),
    RESOLVE_TRANSACTION(Scope.NONE),
    LIST_TRANSACTIONS(Scope.NONE),
    RUN_SCRIPT(Scope.DATABASE),
    SAVE_PROCEDURE(Scope.DATABASE),
    DELETE_PROCEDURE(Scope.DATABASE),
    LIST_PROCEDURES(Scope.DATABASE),
    CALL_PROCEDURE(Scope.DATABASE),
    SAVE_TRIGGER(Scope.COLLECTION),
    DELETE_TRIGGER(Scope.COLLECTION),
    LIST_TRIGGERS(Scope.OPTIONAL_COLLECTION),
    SAVE_SCHEDULE(Scope.DATABASE),
    DELETE_SCHEDULE(Scope.DATABASE),
    LIST_SCHEDULES(Scope.DATABASE),
    LIST_SCRIPTS(Scope.NONE),
    CANCEL_SCRIPT(Scope.NONE),
    TEST_TRIGGER(Scope.COLLECTION),
    LIST_TRIGGER_RUNS(Scope.NONE),
    RESOLVE_TRIGGER_RUN(Scope.NONE),
    ARM_FAULT(Scope.NONE),
    AWAIT_FAULT(Scope.NONE),
    RELEASE_FAULT(Scope.NONE);
    // @formatter:on

    public enum Scope {
        DATABASE, COLLECTION, OPTIONAL_COLLECTION, NONE
    }

    private final Scope scope;

    OperationType(Scope scope) {
        this.scope = scope;
    }

    public Scope scope() {
        return scope;
    }
}
